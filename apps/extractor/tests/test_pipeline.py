"""Extraction behaviour on real (synthetic) media.

These run OpenCV for real — the videos are generated by the test — and fake only the three
model-backed analyzers. See `backends.py` for why that split is the useful one.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from extractor.backends import BackendUnavailable, NoAudioTrack
from extractor.features import FEATURE_SCHEMA_VERSION
from extractor.pipeline import extract
from extractor.testing import (
    FailingBackend,
    FakeAudio,
    FakeOcr,
    FakeTranscriber,
    make_corrupt,
    make_image,
    make_video,
)
from extractor.video import UnreadableMedia


@pytest.fixture
def video(tmp_path: Path) -> Path:
    # 3 flat-colour scenes over 3 seconds → cuts at 1.0s and 2.0s.
    return make_video(tmp_path / "ad.mp4", scenes=3, seconds=3.0, fps=24)


class TestHappyPath:
    def test_a_short_video_yields_a_complete_row(self, video: Path) -> None:
        features = extract(
            video,
            media_type="video",
            ocr=FakeOcr(frames_with_text={0, 1, 2}),
            transcriber=FakeTranscriber(),
            audio=FakeAudio(),
        )

        assert features.skipped_features == []
        assert features.duration_s == pytest.approx(3.0, abs=0.05)
        assert features.first_cut_time_s == pytest.approx(1.0, abs=0.1)
        assert features.cuts_per_second == pytest.approx(2 / 3, abs=0.1)
        assert features.text_in_first_2s is True
        assert features.text_density == pytest.approx(0.5, abs=0.01)
        assert features.first_line_transcript == "primera línea"
        assert features.full_transcript == "primera línea segunda línea"
        assert features.audio_energy_variance == pytest.approx(0.0125)
        assert features.schema_version == FEATURE_SCHEMA_VERSION
        assert features.truncated is False

    def test_text_after_the_hook_window_does_not_set_text_in_first_2s(self, video: Path) -> None:
        # Frames are sampled every 0.5s, so index 4 is t=2.0s — the first frame outside the
        # hook window. If this ever passes with `{4}`, the window has drifted.
        features = extract(
            video,
            media_type="video",
            ocr=FakeOcr(frames_with_text={4, 5}),
            transcriber=FakeTranscriber(),
            audio=FakeAudio(),
        )
        assert features.text_in_first_2s is False
        assert features.text_density and features.text_density > 0

    def test_low_confidence_detections_are_discarded(self, video: Path) -> None:
        # A backend that reports texture and logos as text would drive text_density to 1.0
        # for every creative, erasing the contrast the feature exists to provide.
        features = extract(
            video,
            media_type="video",
            ocr=FakeOcr(frames_with_text={0, 1, 2, 3, 4, 5}, confidence=0.2),
            transcriber=FakeTranscriber(),
            audio=FakeAudio(),
        )
        assert features.text_density == 0.0
        assert features.text_in_first_2s is False
        assert "text_density" not in features.skipped_features


class TestMeasuredAbsenceVersusUnmeasurable:
    """The distinction the whole degradation design rests on."""

    def test_a_single_shot_video_has_no_cut_and_is_not_a_skip(self, tmp_path: Path) -> None:
        single = make_video(tmp_path / "single.mp4", scenes=1, seconds=2.0, fps=24)

        features = extract(single, media_type="video", ocr=FakeOcr(), transcriber=FakeTranscriber())

        # Measured absent: the advertiser genuinely never cut. `cuts_per_second == 0` is
        # the disambiguator — a null there would mean we could not look.
        assert features.first_cut_time_s is None
        assert features.cuts_per_second == 0.0
        assert "first_cut_time_s" not in features.skipped_features
        assert "cuts_per_second" not in features.skipped_features

    def test_a_missing_audio_backend_is_a_skip_not_a_zero(self, video: Path) -> None:
        features = extract(video, media_type="video", ocr=FakeOcr(), transcriber=FakeTranscriber())

        # A zero here would put the creative in the n for audio_energy_variance and drag
        # its cohort mean toward zero. The skip keeps it out.
        assert features.audio_energy_variance is None
        assert "audio_energy_variance" in features.skipped_features

    def test_a_silent_track_is_reported_as_a_skip(self, video: Path) -> None:
        features = extract(
            video,
            media_type="video",
            ocr=FakeOcr(),
            transcriber=FakeTranscriber(),
            audio=FailingBackend(NoAudioTrack("no audible audio")),
        )
        assert features.audio_energy_variance is None
        assert features.skipped_features == ["audio_energy_variance"]

    def test_a_music_only_video_transcribes_to_empty_without_a_skip(self, video: Path) -> None:
        # The model ran and heard no speech. That is a real measurement about the creative,
        # not a failure to measure, and music-only ads are common enough to matter.
        features = extract(
            video,
            media_type="video",
            ocr=FakeOcr(),
            transcriber=FakeTranscriber(lines=()),
            audio=FakeAudio(),
        )
        assert features.full_transcript == ""
        assert features.first_line_transcript is None
        assert "full_transcript" not in features.skipped_features


class TestGracefulDegradation:
    def test_a_failing_ocr_backend_does_not_fail_the_job(self, video: Path) -> None:
        features = extract(
            video,
            media_type="video",
            ocr=FailingBackend(RuntimeError("model exploded")),
            transcriber=FakeTranscriber(),
            audio=FakeAudio(),
        )

        assert features.text_density is None
        assert features.text_in_first_2s is None
        assert set(features.skipped_features) == {"text_in_first_2s", "text_density"}
        # The cheap geometric features survive a model failure — that is the point.
        assert features.duration_s is not None
        assert features.cuts_per_second is not None

    def test_a_missing_optional_dependency_degrades(self, video: Path) -> None:
        features = extract(
            video,
            media_type="video",
            ocr=FakeOcr(frames_with_text={0}),
            transcriber=FailingBackend(BackendUnavailable("faster-whisper not installed")),
            audio=FailingBackend(BackendUnavailable("librosa not installed")),
        )
        assert set(features.skipped_features) == {
            "first_line_transcript",
            "full_transcript",
            "audio_energy_variance",
        }
        assert features.text_in_first_2s is True

    def test_every_analyzer_failing_still_yields_a_row(self, video: Path) -> None:
        boom = FailingBackend(RuntimeError("boom"))
        features = extract(video, media_type="video", ocr=boom, transcriber=boom, audio=boom)

        assert features.duration_s is not None
        assert len(features.skipped_features) == 5


class TestStaticImage:
    def test_an_image_yields_nulls_and_a_populated_skip_list(self, tmp_path: Path) -> None:
        image = make_image(tmp_path / "ad.jpg")

        features = extract(image, media_type="image", ocr=FakeOcr(frames_with_text={0}))

        assert features.duration_s is None
        assert features.cuts_per_second is None
        assert features.audio_energy_variance is None
        # Skipped rather than zeroed: "this medium cannot cut" is not the same fact as
        # "the advertiser chose not to cut", and cohort math must not merge them.
        assert set(features.skipped_features) == {
            "duration_s",
            "first_cut_time_s",
            "cuts_per_second",
            "first_line_transcript",
            "full_transcript",
            "audio_energy_variance",
        }
        assert features.text_in_first_2s is True
        assert features.text_density == 1.0

    def test_an_image_without_text_reports_zero_density(self, tmp_path: Path) -> None:
        image = make_image(tmp_path / "plain.jpg")
        features = extract(image, media_type="image", ocr=FakeOcr())
        assert features.text_density == 0.0
        assert features.text_in_first_2s is False


class TestCapAndTruncation:
    def test_a_long_video_is_truncated_not_skipped(self, tmp_path: Path) -> None:
        long_video = make_video(tmp_path / "long.mp4", scenes=5, seconds=5.0, fps=24)

        features = extract(
            long_video,
            media_type="video",
            ocr=FakeOcr(),
            transcriber=FakeTranscriber(),
            audio=FakeAudio(),
            cap_s=2.0,
        )

        assert features.truncated is True
        assert features.analysis_cap_s == 2.0
        # Duration is the true duration of the ad; the cap governs what was *sampled*.
        # Reporting the capped length as the duration would shorten every long creative.
        assert features.duration_s == pytest.approx(5.0, abs=0.1)
        # The rate is over what we looked at, not over the whole ad: 2 cuts in the 2s
        # sampled is 1.0/s. Dividing by the full 5s duration would report 0.4/s — a rate
        # for a stretch of the ad that was never examined, biased downward by exactly the
        # truncation ratio. `> 0` passes under both, so it must be the exact value.
        assert features.cuts_per_second == pytest.approx(1.0)

    def test_a_video_shorter_than_the_cap_is_not_marked_truncated(self, video: Path) -> None:
        features = extract(video, media_type="video", ocr=FakeOcr(), cap_s=120.0)
        assert features.truncated is False


class TestUnreadableMedia:
    def test_a_corrupt_file_raises_rather_than_writing_a_row_of_nulls(self, tmp_path: Path) -> None:
        corrupt = make_corrupt(tmp_path / "broken.mp4")

        # A row of nulls would read downstream as "we measured this and found nothing".
        # There is nothing to measure, so this is a failed job with a reason instead.
        with pytest.raises(UnreadableMedia):
            extract(corrupt, media_type="video", ocr=FakeOcr())

    def test_a_missing_file_raises(self, tmp_path: Path) -> None:
        with pytest.raises(UnreadableMedia):
            extract(tmp_path / "nope.mp4", media_type="video", ocr=FakeOcr())
